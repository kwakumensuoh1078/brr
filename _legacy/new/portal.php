                                                proposed policies and regulations are anticipated and considered by Government, and cumulative or overlapping regulations are avoided. 
                                                Inputs from the Business Consultation portal will feed into Regulatory Impact Analysis and significantly improve the evidence basis for 
                                                Inter-Ministerial decision-making. </p>

                                                <p>
                                                The functions and indicative features of the Ghana Business Consultation Portal are:
    
                                                <ul>
                                                    <li>The Business Consultation Portal will primarily focus on building an online community of users to participate in consultations on business policies and regulatory reforms on a regular basis. Ministries, Departments and Agencies (MDAs) will have the opportunity to consult with a wider and more diverse audience than is practically possible at public forums and workshops.
                                                </li>
                                                <li> The portal will connect businesses, individuals, industry associations and not-for-profit organisations with Government, Ministries, Departments and Agencies (MDAs), with a schedule of upcoming consultations on draft policies and regulations announced and published on the Portal in advance by MDAs. Encouraging repeat participation will be a very important factor for optimizing the usage of the Portal.
                                                </li>
                                                <li> The Portal can be used to conduct either public or direct consultations. A public consultation is a consultation that is private and sent to selected registered businesses and individuals. It allows Government to interact directly with people who offer /register to be consulted when business policies and regulations are being developed or improved.
                                                </li>
                                                <li> Businesses, individuals, industry associations, policy think tanks, civil society and not-for-profit organisations can register to have their details supplied to the relevant Ministries, Departments and Agencies (MDAs). These details will be used when a consultation request is being made. They could be notified by email when public consultations relevant to their selected interests are posted on the Portal.
                                                </li>
                                                <li> The Portal will provide the private sector and other economic operators (individuals from labour, consumer protection, economic policy think-tanks and civil society) with virtual opportunities to contribute publicly or directly to discussions with Government on improving specific business policies and regulations.              
