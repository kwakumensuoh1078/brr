                             <h6>Rolling Review of business regulations, using Regulatory Guillotine principles</h6>
   
                                        <p>
                                        Rolling Review of Regulations is a sustainable way of updating and maintaining up-to-date business regulations to provide 
                                        transparency and predictability to the private sector businesses. It adopts a systematic and step by step assessment of a 
                                        regulatory field to review business regulations affecting sectors of the market in order to improve the market quality. 
                                        It relies on a methodological review approach and strategy to carry out the rolling review of all business-related laws and 
                                        regulations on the electronic database.<br/> The Rolling Review begins with the configuration and development of evaluation and 
                                        assessment schemes with key operational guidelines and review strategies. The implementation outcome of the Rolling Review of 
                                        the regulations includes a detailed content analysis targeting the following tasks: 
                                        <br/>
                                            (a)assessment of the quality of business-related regulations, </br>
                                            (b)cleaning the regulatory field of regulations that do not correspond with a validated evaluation index and </br>
                                            (c)preparation of recommendations regarding the system regulatory improvement. In accordance with the 
                                        assessment results of Rolling Review, one out of three (3) possible outcomes may be reached in respect of any single business 
                                        regulation:
                                        </br>
                                            <1>Remove/Repeal/delete </br> 
                                            <2> Maintain</br>
                                            <3>Review/Amend </br> </p>
