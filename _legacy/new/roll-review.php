                                          <dt class="faq_header active">Legality<span class="icon-play"></span>
                                          </dt>
                                          <dd class="accordion-content hide" style="display:block;">
                                             <p align='justofy'>
                                                 The term ‘legality’ to refer to the identification of variables that assess the process of adoption, enactment, 
                                                 and entry into force of the regulation. A legitimate law or regulation would have complied with the procedure 
                                                 drawn under the law for its enactment and entry into force. This assessment is in the context of a number of 
                                                 overarching themes relating to the legal status of the regulation, namely, compliance with enactment or adoption 
                                                 procedure as made by an authorized body and an evaluation of its current status. The assessment will also include a 
                                                 determination of whether or not the regulation is affected by any repeal(s) currently in force.   
                                                 <br><br>
                                                 <b>Context of assessment: </b><br>Within the context of its review, the legitimacy of the law as it establishes its Legality is measured against three key indexes. 
                                                 <br>
                                                     (a) Is this regulation duly enacted in accordance with law?<br>
                                                      (b) Is this regulation gazetted?<br>
                                                      (c) Is this regulation repealed by another regulation or enacting body?
                                                 </p>
                                          </dd>
                                          <dt class="faq_header">Currency<span class="icon-play"></span>
                                          </dt>
                                          <dd class="accordion-content hide">
                                             <p align='justofy'>
                                              This indicator assesses the content of the regulation by analysing its currency. It proceeds by identifying whether the regulation is affected by any amendment or repeal 
                                              and by determining whether the content of the regulation has been adjusted to reflect all amendments and repeals made thereto. To an extent, it also assesses whether the 
                                              law has been periodically amended to meet the current operational policies or whether it is outdated.<br> 
<b> Context of assessment:</b><br> Within the context of its review, the Currency of the law is measured against four key indexes. <br>                                       
(i)	Is the law affected by any amendment?<br> 
(ii)	Is the law affected by any repeals?<br> 
(iii)	Does the content of the regulation reflect applicable amendments and repeals?<br> 
(iv)	Is the law outdated?
</p>
                                          </dd>
                                          <dt class="faq_header">
                                            Relevance<span class="icon-play"></span>
                                          </dt>
                                          <dd class="accordion-content hide">
                                             <p>
                                               With this indicator, the Rolling Review Team assesses the status of compliance by the regulation with modern trends in business and trade as well as international obligations adopted under treaties and other internationally binding documents.  
<br><b> Context of assessment: </b><br>Within the context of its review, Relevance is measured against four key indexes.  <br>                                      
(i)	Does the regulation promote the doing of business?  <br>  
(ii)	Does the regulation promote the objectives of the industry? <br>  
(iii)	Is the regulation in line with modern trends in trade and business? <br>  
(iv)	Does the regulation comply with international obligation(s) assumed by the country?
 </p>
                                          </dd>
                                          <dt class="faq_header">
                                            Regulation Necessity<span class="icon-play"></span>
                                          </dt>
                                          <dd class="accordion-content hide">
                                             <p>
In this context, the assessment is dependent on the consideration of two criteria, namely the ‘effectiveness’ of the regulation and also its ‘usefulness’.  
Effectiveness of a regulation is defined as the successful achievement of the purpose for which it was enacted. This criterion is determined based on the 
memorandum and underlying objectives of the regulation or its regulatory impact assessment. 


<b> Context of assessment: </b><br>Within the context of its review, Regulation Necessity is measured against five key indexes, grouped into two groups for ease of analysis.                                      
The indexes for the ‘effectiveness review’ are as follows: <br>                                      
(i)	Is the purpose for the adoption or enactment of the regulation clear? <br>  
(ii)	Has the regulation achieved its underlying objectives? <br>  
The usefulness of the regulation is defined on the basis of the solutions to the core problems for which the regulation is made. The indexes for determination of the usefulness of the regulation are:
<br>
(iii)	Has the regulation been successful in addressing the concern for which it was enacted? <br>  
(iv)	Has the implementation of the regulation enhanced the doing of business in the market, business or industry?<br>
(v) Is the regulation devoid of provisions that are inimical to the achievement of the overall objective of its enactment?
 </p>
                                          </dd>
                                          
                                          <dt class="faq_header">
                                            Convenience<span class="icon-play"></span>
                                          </dt>
                                          <dd class="accordion-content hide">
                                             <p>
assesses the convenience of the regulation in promoting business generally. It focuses on convenience in relation to the use of the regulation as well as 
convenience in terms of ease of compliance with prescribed procedures established by the regulation for the accomplishment of a task.  

<b> Context of assessment: </b><br>Within the context of its review, Relevance is measured against four key indexes.  <br>                                      
(i)	Is the regulation accessible or available to the public?  <br>  
(ii)	Is the regulation clear enough in terms of language and meaning? <br>  
(iii)	Does the regulation clearly prescribe the procedures for complying with stated requirements? <br>  
(iv)	Are the procedures comprehensive enough? <br>
(v) Are the procedures flexible? <br>
(vi) Is the regulation devoid of administrative difficulties, complexities and inconsistencies in its implementation? <br>
(vii)Are the penalties prescribed for prohibited acts or omissions clear, consistent and reasonable? 
 
 </p>
                                          </dd>
                                          <dt class="faq_header">
                                            Costs on Business<span class="icon-play"></span>
                                          </dt>
                                          <dd class="accordion-content hide">
                                             <p>
This assesses the content of the regulation by evaluating processes and procedures for the accomplishment of a task. 
The assessment involves an analysis of all processes that impose or result in costs to the business, and by examining fees for registration, 
acquisition of permits, licences, as well as administrative and other expenses attached to the conduct of business.. 
<br>                                      

<b> Context of assessment: </b><br> Within the context of its review, Costs on Business is measured against five key indexes.  <br>                                      
(i)	Are the processes resulting in cost or fee necessary?  <br>  
(ii)	Are the imposed costs or fees necessary? <br>  
(iii)	Are the imposed costs or fees reasonable? <br>  
(iv)	Are the costs or fees clearly stated?<br>
(v) Have the costs or fees been duly reviewed periodically? 
 
 </p>
                                          </dd>
                                          
                                          <dt class="faq_header">
                                            Efficiency<span class="icon-play"></span>
                                          </dt>
                                          <dd class="accordion-content hide">
                                             <p>
This examines key evaluation questions to assess whether any particular regulation is appropriate, effective and efficient. The Team assesses the degree and level of 
achievement of the particular objectives of the regulation and the appropriateness of its processes and procedures. The assessment also responds to the query whether 
the content and objective of the law align with government’s policies within the relevant industry. This assessment focuses on the functions and scope of the regulation 
and evaluates its overall content along key variables that determine whether the regulation is in support of current policy objectives within the broad ministerial 
mission of easing the doing of business in Ghana and promotion of industrial transformation.

<br>                                      

<b> Context of assessment: </b><br> Within the context of its review, the Efficiency of the law is measured against six key indexes  <br>                                     
<i> (a)	Statement of purpose</i> <br>  
(i)		Does the regulation have a clear statement of objective? <br>  
(ii)	Does the content of the regulation meet its overall objective? <br>  
(iii)	Is the regulation in furtherance of current government policy in the industry?<br> <br>  
<i> (b)	Implementation</i><br>  
(iv)	Has the regulation been implemented?<br>
(v) Are the processes and procedures favourable to achieve the overall objective of the regulation?<br>  
(vi) Are the processes and procedures cost-effective?
 
 </p>
                                          </dd>
                                          
                                          <dt class="faq_header">
                                            Corruption Risks<span class="icon-play"></span>
                                          </dt>
                                          <dd class="accordion-content hide">
                                             <p>
examines corruption risks and their impact on business processes and the overall effect on the doing of business. The review identifies processes and procedures that respond to the existence of unguarded discretion, subjectivity, lack of clarity, ambiguities and lack of accountability or absence of reporting systems
Context of assessment: Within the context of its review, Corruption is measured against ten key indexes.  <br>                                      
The level of corruption risks is determined as an aggregate index of a series of assessments of corruption in the regulation by responding to the following questions: 
 

<br>                                      

<b> Context of assessment: </b><br> Within the context of its review, Costs on Business is measured against five key indexes.  <br>                                      
(i)	Does the regulation provide for any procedure involving decisions to be made by a public official affecting a business? <br>  
(ii)	Does the regulation provide a procedure that gives the power to a public official to refuse an application based on some defects or insufficiencies affecting the application?  <br>  
(iii)	Are the requirements for the subject clearly defined so that ambiguous construction is prevented? 
<br>  
(iv)	Can an official request from the applicant any other document/information, in addition to those that are expressly required by the regulation?
<br>
(v) Does the regulation include an exhaustive list of options for taking official action on each of the situations that may occur in the implementation of the act? <br>
(vi) Does the regulation include an exhaustive list of grounds or conditions governing a particular application or the execution of a particular task?
<br>
(vii) Does the regulation include a clear deadline for decisions required to be made by officials in respect of applications made before them? 
<br>
(viii) Does the regulation require the public official to justify the decision in writing in case of an adverse decision? <br>
(ix)	Is there a possibility to appeal the official’s decision to a higher authority or court of competent jurisdiction? 

 </p>
                                          </dd>
                                          
                                          <dt class="faq_header">
                                            Impact on Business<span class="icon-play"></span>
                                          </dt>
                                          <dd class="accordion-content hide">
                                             <p>
This conducts an assessment of the impact of the regulation on the extent and nature of its impact on doing business generally.
<br>                                      

<b> Context of assessment: </b><br> Within the context of its review, Impact on Business is measured against six key indexes.  <br>                                      
(i)	Does the regulation impose any significant restrictions or prohibitions in respect of certain activities?                           
 <br>  
(ii)Does the regulation provide a clear list of conditions that must be fulfilled to be eligible to carry out the particular economic activity?  <br> 
(iii)Are the conditions imposed in the particular business reasonable?<br>  
(iv)Does the regulation provide for mandatory payments?<br>
(v) Does the Regulation control and oversee the power of the regulator to make decisions that may significantly affect the business environment?
 <br>
(vi) Does the Regulator make it voluntary for businesses to use the services of third parties as part of a process to fulfil a requirement? 


 </p>
                                          </dd>
                                          
                                           <dt class="faq_header">
                                            Conflicts<span class="icon-play"></span>
                                          </dt>
                                          <dd class="accordion-content hide">
                                             <p>
This considers matters of relational legitimacy and overlapping regulations and provisions. The assessment requires a verification of the existence or otherwise of contradictions within the same regulation and inter-regulations, as well as matters tainted with duplications and overlaps among regulations. The context also extends to an analysis of the harmonization of the contents of regulations and how lower laws within the hierarchy and priority in the regulatory field accord with their higher substantive statutes and regulations.

<br>                                      

<b> Context of assessment: </b><br> Within the context of its review, Conflict is measured against four key indexes.  <br>                                      
(i)	Does the regulation have any internally conflicting provisions?                         
 <br>  
(ii)Does the regulation conflict with another regulation?  <br> 
(iii)Does the regulation overlap with another regulation?<br>  
(iv)Does the regulation fit the context of its enactment or adoption? 


 </p>
