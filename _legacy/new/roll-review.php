                                <!--===============spacing==============-->
                                <div class="pd_bottom_25"></div>
                                <!--===============spacing==============-->
                                
                                <p align='justify'> The establishment of this Rolling Review process has been guided by a number of evaluation indexes stated in 
                                specific and individualized tasks designed to achieve the key objectives of the review exercise: <br>
                                
                                    (a) Review of regulations by evaluating existing regulations to identify those that should be repealed, replaced, or modified<br>
                                     (b)Assessment of impact of regulations and their provisions to systematically ensure that they meet their intended objectives efficiently and 
                                    effectively in a changing and complex economic and social environment. <br>
                                     (c)Assessment of implementation procedures<br>
                                     (d)Ensuring that regulations, regulatory institutions charged with implementation, and regulatory processes are transparent and non-discriminatory. <br>
                                     (3) Design economic regulations in all sectors to stimulate competition and efficiency and eliminate all regulations that militate against this objective except where clear evidence demonstrates that they are the best way to serve broad public interests.<br>
                                
                                 </p>
                                 
                                 <p align='justify'> 
                                The practical effects of the review will be the identification of regulations that: 
                                <ol type='a'>
                                    <li> inhibit business growth and development</li>
                                    <li> are outdated, unnecessary, or ineffective </li>
                                    <li> impose costs that exceed benefits </li>
                                    <li> create a serious inconsistency or otherwise interfere with regulatory reform initiatives and policies</li>
                                    <li> are inconsistent with the Government’s agenda for improving the business environment</li>
                                    <li>have gaps and weaknesses and suggest ways that support reform. </li>
                                    <li> 	fail to adopt at the political level, broad programmes of regulatory reform that establish clear objectives and frameworks for implementation </li>
                                    </ol>
                                It is hereby generated an administrative strategy to enable a highly structured Rolling Review process with clear filters and incentives for reform. 
                                A report on the implementation will outline proposed reviews and make critical recommendations for review, amendment or repeal of regulatory requirements that 
                                the Rolling Review Team finds outdated, ineffective, or excessively burdensome especially for the growth and development of the private sector.
                                </p>
